// Generates a single, self-contained SQL file that (re)creates the clean
// "Gates Ridge Civic Association" community under invite code GATES, seeded from
// the vendor list in scripts/gates-data.json.
//
//   node scripts/gen-gates-sql.mjs > supabase/seed-gates.sql
//
// The output: deletes any existing GATES/GATES2 community (cascades to members,
// vendors, vouches), then inserts the community, one member per unique
// recommender, deduped vendors (by last-10 phone digits), and a vouch per
// recommendation. All ids/tokens are pre-generated here so the SQL has no
// ordering or lookup dependencies. Run it in the Supabase SQL editor.
//
// Expected gates-data.json shape (array of rows):
//   { recommender, name, type, phone, contact, notes }
import { readFileSync } from 'fs';
import { randomUUID } from 'crypto';
import { mapType } from './type-map.mjs';

const COMMUNITY = {
  name: 'Gates Ridge Civic Association',
  code: 'GATES',
  join_policy: 'open',
  signon_method: 'off', // name-only sign-on
};

const digits = (p) => (p ?? '').replace(/\D/g, '').slice(-10);
// Single-quote escape for SQL string literals.
const q = (v) => (v == null ? 'NULL' : `'${String(v).replace(/'/g, "''")}'`);

const rows = JSON.parse(readFileSync('scripts/gates-data.json', 'utf8'));

const cid = randomUUID();
const out = [];
out.push('-- Clean seed for Gates Ridge Civic Association (code GATES).');
out.push('-- Generated by scripts/gen-gates-sql.mjs. Run in the Supabase SQL editor.');
out.push('begin;');
out.push('');
out.push("-- Remove the old/messy community and this code if re-running (cascades).");
out.push("delete from vouch_communities where code in ('GATES', 'GATES2');");
out.push('');
out.push('-- Community');
out.push(
  `insert into vouch_communities (id, name, code, join_policy, signon_method) values\n` +
    `  (${q(cid)}, ${q(COMMUNITY.name)}, ${q(COMMUNITY.code)}, ${q(COMMUNITY.join_policy)}, ${q(COMMUNITY.signon_method)});`
);
out.push('');

// One member per unique recommender (blank rows fall back to a directory name).
const memberIds = new Map();
const names = [...new Set(rows.map((r) => r.recommender || 'Gates Directory'))];
const memberValues = names.map((name) => {
  const id = randomUUID();
  memberIds.set(name, id);
  return `  (${q(id)}, ${q(cid)}, ${q(name)}, ${q(randomUUID())}, 'member', 'approved')`;
});
out.push('-- Members (one per recommender; no admin yet — promote later)');
out.push(
  `insert into vouch_members (id, community_id, name, token, role, status) values\n` +
    memberValues.join(',\n') +
    ';'
);
out.push('');

// Vendors (dedup by phone) + vouches.
const seenPhones = new Map(); // digits -> vendor id
const vendorValues = [];
// vouch_vouches is unique on (vendor_id, member_id): if the same recommender
// lists the same (deduped) vendor twice, collapse to one vouch and merge the
// comments so no note is lost.
const vouches = new Map(); // `${vendorId}|${memberId}` -> Set<comment>
function addVouch(vendorId, memberId, comment) {
  const key = `${vendorId}|${memberId}`;
  if (!vouches.has(key)) vouches.set(key, { vendorId, memberId, comments: new Set() });
  if (comment) vouches.get(key).comments.add(comment);
}

for (const r of rows) {
  const memberName = r.recommender || 'Gates Directory';
  const memberId = memberIds.get(memberName);
  const vendorName = r.name || r.contact || r.type || 'Unnamed';
  const comment =
    [r.notes, r.contact && r.contact !== vendorName ? `Ask for ${r.contact}.` : null]
      .filter(Boolean)
      .join(' ') || null;

  const d = digits(r.phone);
  if (d.length >= 7 && seenPhones.has(d)) {
    // Same number already listed — attach this person's vouch to that vendor.
    addVouch(seenPhones.get(d), memberId, comment);
    continue;
  }

  const vid = randomUUID();
  if (d.length >= 7) seenPhones.set(d, vid);
  vendorValues.push(
    `  (${q(vid)}, ${q(cid)}, ${q(vendorName)}, ${q(mapType(r.type))}, ${q(r.phone)}, NULL, ${q(memberId)})`
  );
  addVouch(vid, memberId, comment);
}

const vouchValues = [...vouches.values()].map(
  (v) => `  (${q(v.vendorId)}, ${q(v.memberId)}, '{}', ${q([...v.comments].join(' ') || null)})`
);

out.push('-- Vendors (deduped by phone)');
out.push(
  `insert into vouch_vendors (id, community_id, name, category, phone, contact, added_by) values\n` +
    vendorValues.join(',\n') +
    ';'
);
out.push('');
out.push('-- Vouches (tags empty; rating retired)');
out.push(
  `insert into vouch_vouches (vendor_id, member_id, tags, comment) values\n` +
    vouchValues.join(',\n') +
    ';'
);
out.push('');
out.push('commit;');
out.push('');

process.stdout.write(out.join('\n'));
process.stderr.write(
  `Generated SQL: 1 community, ${memberIds.size} members, ${vendorValues.length} vendors, ${vouchValues.length} vouches.\n`
);
